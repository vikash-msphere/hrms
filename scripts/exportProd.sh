#!/usr/bin/env bash
#
# Export the deployable subset of this repo into a clean tree, ready to push to a separate repo.
#
# What "deployable" means here: everything `npm ci && npm run deploy` touches (Worker sources, the SPA, the
# prod bootstrap catalog, the verify gate, the deploy workflow) and nothing else. Dev tooling, docs, design
# assets, demo/seed data and scratch files stay behind - see EXCLUDED at the bottom of this header for the
# list and the reason each one is safe to drop.
#
# Usage (from anywhere):
#   scripts/exportProd.sh                        # export to $DEST_DEFAULT below
#   scripts/exportProd.sh ~/git/hrms-prod        # export to a directory of your choice
#   DEST=~/git/hrms-prod scripts/exportProd.sh   # same, via the environment
#
# Flags:
#   --force              wipe the destination if it already exists (refuses otherwise)
#   --no-illustrations   skip web/public/assets/illustrations (24 MB / ~1700 files). The announcement
#                        IllustrationPicker renders empty; nothing else changes.
#   --no-tests           omit test/ + vitest.config.ts, narrow `verify` to api:lint + typecheck, and add the
#                        node types to tsconfig (test/ is what pulls them in today). Loses the deploy gate.
#   --no-git             leave the tree as plain files (default: git init + one commit on `main`)
#   --secrets-example    also copy .dev.vars.example (the secret NAMES). Off by default - read the file first.
#   --verify             prove the export: symlink this repo's node_modules into it and run api:lint,
#                        typecheck, build:web and the full suite there. Takes ~2 min.
#
# Always runs an import-closure scan over every exported .ts/.tsx/.mjs/.js: a relative or `@/` import that
# resolves to a file NOT in the export fails the run. src/http/openapi.d.ts is the one expected miss - it is
# generated by `npm run api:types` and deliberately gitignored.
#
# EXCLUDED, with the reason (all verified to have no code references):
#   docs/ misc/ tmp/ README.md web/README.md ux-*-plan.md cf.txt   not read at runtime or build
#   dist/                      build output of the old root-level asset-tag mock, not the SPA
#   branding.json              design tokens; the values are hardcoded in src/domain/brand.ts + index.css
#   CCAIndia2022.cer           the eSign trust anchors are inlined in web/src/lib/ccaRoots.ts
#   logo*.svg/png ms-logo* Metasphere.svg favicon.svg (root)   the shipped icons live in web/public/
#   scripts/*                  everything except the seven files EXPORT_SCRIPTS lists below, plus
#                              e2eStack.sh, which ships with the browser lane
#   bootstrap/genDemo.ts bootstrap/demo.sql scripts/seed.sql   demo/dev data, never applied to production
#   .dev.vars .vapid.json      secrets - set them with `wrangler secret put`
#   .mcp.json aep              editor/CLI tooling; `aep` is a local macOS binary, api:lint runs from npm
#   .claude/ .vscode/ .repowise/ .tokensave/ .wrangler/ web/dist/ test-results/ node_modules/   local state
#                              and build output
#   .github/workflows/e2e.yml  the browser lane is exported, but nothing there runs it - see below
#
# THE BROWSER LANE (e2e/, playwright.config.ts, scripts/e2eStack.sh) is exported as source and is wired into
# nothing that runs on its own:
#   - `.github/workflows/e2e.yml` is skipped while the other workflows are copied, so no CI job starts a
#     browser. `verify` (spectral + tsc + vitest) and `deploy` never invoked it in the first place.
#   - `typecheck` still typechecks e2e/tsconfig.json. That is a tsc pass over the specs, not a browser run,
#     and it is what keeps them honest about the app modules they import (src/lib/session).
#   - `npm run test:e2e` is run by hand or not at all. It needs a database seeded from scripts/seed.sql +
#     scripts/templates.sql, which are demo data and stay behind, so the lane does not boot in a bare clone
#     of the export: bring those two files over yourself when you want to run it.
# e2e/e2e.vars goes with it. It is not a secrets file: every value is a test-only stand-in (all-zero keys, a
# fake client id), the same shape vitest.config.ts binds, and the real ones are Worker secrets.
# --no-tests drops the lane along with test/, since typecheck would then point at a project that is gone.
# @playwright/test is already in devDependencies and stays there - package-lock.json is copied verbatim and
# `npm ci` fails on any package.json that disagrees with it.
#
# Three tests are pruned because they import the demo/seed SQL as raw data (nothing left to guard once the
# seed files are gone): see SEED_TESTS below.
set -euo pipefail

DEST_DEFAULT="${HOME}/git/hrms-prod"   # edit this, or pass a directory / set DEST=

FORCE=0
ILLUSTRATIONS=1
TESTS=1
GIT=1
VERIFY=0
SECRETS_EXAMPLE=0
DEST="${DEST:-}"

for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    --secrets-example) SECRETS_EXAMPLE=1 ;;
    --no-illustrations) ILLUSTRATIONS=0 ;;
    --no-tests) TESTS=0 ;;
    --no-git) GIT=0 ;;
    --verify) VERIFY=1 ;;
    -h|--help) sed -n '2,61p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "✗ unknown flag: $arg (try --help)" >&2; exit 1 ;;
    *) DEST="$arg" ;;
  esac
done
DEST="${DEST:-$DEST_DEFAULT}"

cd "$(dirname "$0")/.."   # project root
ROOT="$PWD"

# Expand ~ and make the path absolute BEFORE any rm -rf touches it.
DEST="${DEST/#\~/$HOME}"
case "$DEST" in /*) ;; *) DEST="$PWD/$DEST" ;; esac
if [ "$DEST" = "$ROOT" ]; then echo "✗ destination is the source repo. Pick another directory." >&2; exit 1; fi

if [ -e "$DEST" ]; then
  if [ "$FORCE" = 1 ]; then
    echo "→ wiping $DEST (--force)"; rm -rf "$DEST"
  elif [ -n "$(ls -A "$DEST" 2>/dev/null)" ]; then
    echo "✗ $DEST exists and is not empty. Pass --force to replace it." >&2; exit 1
  fi
fi
mkdir -p "$DEST"
echo "→ exporting to $DEST"

# --- what goes in ------------------------------------------------------------------------------------------

# Whole trees. --claude/-junk exclusions apply to every one of them.
EXPORT_TREES=(src bootstrap)
# Root-level config. Each one is on the `npm ci` / typecheck / build / deploy path.
EXPORT_ROOT=(
  package.json package-lock.json   # deps + lockfile
  wrangler.toml                    # main, [assets], D1/R2/KV bindings, crons, vars
  tsconfig.json                    # Worker + test typecheck
  openapi.yaml                     # api:types generates src/http/openapi.d.ts, imported by src/http/wire.ts
  .spectral.yaml                   # ruleset for api:lint
  drizzle.config.ts                # db:generate, for future schema changes
  .gitignore
)
# web/ config. The SPA root is ./web (vite.config.ts `root`), output ../web/dist.
EXPORT_WEB=(index.html vite.config.ts tsconfig.json tailwind.config.js postcss.config.js .env .env.example)
# scripts/ - only the files the deploy path or bootstrap/ actually import.
EXPORT_SCRIPTS=(
  tsResolve.mjs           # ts loader every node script runs through
  preflight.ts            # `npm run deploy` step 1; reads wrangler.toml, web/.env, web/src/lib/ccaRoots.ts
  genAccessRulesSeed.ts   # imported by bootstrap/genBootstrap.ts
  genTemplatesSeed.ts     # imported by bootstrap/genBootstrap.ts
  genSearchDdl.ts         # db:generate step
  genChangeDdl.ts         # db:generate step
  genVapidKeys.ts         # only to mint a new web-push keypair
)
# Tests that read the demo/seed SQL as raw data - meaningless without it.
SEED_TESTS=(test/seedDrift.test.ts test/manifestSeedDrift.test.ts test/seedIdShape.test.ts)

RSYNC_EXCL=(--exclude '.claude' --exclude '.DS_Store' --exclude 'node_modules')

for t in "${EXPORT_TREES[@]}"; do
  rsync -a "${RSYNC_EXCL[@]}" --exclude 'openapi.d.ts' --exclude 'genDemo.ts' --exclude 'demo.sql' "$t" "$DEST/"
done

mkdir -p "$DEST/web"
rsync -a "${RSYNC_EXCL[@]}" --exclude 'web' web/src "$DEST/web/"        # web/src/web is build junk
if [ "$ILLUSTRATIONS" = 1 ]; then
  rsync -a "${RSYNC_EXCL[@]}" web/public "$DEST/web/"
else
  rsync -a "${RSYNC_EXCL[@]}" --exclude 'assets/illustrations' web/public "$DEST/web/"
  echo "  · skipped web/public/assets/illustrations (--no-illustrations)"
fi
for f in "${EXPORT_WEB[@]}"; do
  if [ -e "web/$f" ]; then cp -p "web/$f" "$DEST/web/$f"; else echo "  · web/$f missing, skipped"; fi
done

for f in "${EXPORT_ROOT[@]}"; do cp -p "$f" "$DEST/$f"; done
# .dev.vars.example is NOT copied by default: it sits next to the real .dev.vars and nothing but a reading
# eye keeps a live value from being pasted into it. Pass --secrets-example once you have looked at the file.
if [ "$SECRETS_EXAMPLE" = 1 ] && [ -f .dev.vars.example ]; then
  cp -p .dev.vars.example "$DEST/"
  echo "  · copied .dev.vars.example - confirm it holds NAMES only before pushing"
fi

mkdir -p "$DEST/scripts"
for f in "${EXPORT_SCRIPTS[@]}"; do cp -p "scripts/$f" "$DEST/scripts/$f"; done

mkdir -p "$DEST/.github/workflows"
for f in .github/workflows/*.yml; do
  # The specs are exported; the CI job that drives a browser is not. Nothing in the export starts one.
  case "$(basename "$f")" in e2e.yml) continue ;; esac
  cp -p "$f" "$DEST/.github/workflows/"
done

# husky: only the hook itself. `npm ci` runs `prepare: husky`, which regenerates .husky/_ - but the directory
# has to exist or that command fails and takes `npm ci` down with it.
mkdir -p "$DEST/.husky"
cp -p .husky/pre-commit "$DEST/.husky/"

if [ "$TESTS" = 1 ]; then
  rsync -a "${RSYNC_EXCL[@]}" test "$DEST/"
  cp -p vitest.config.ts "$DEST/"
  for f in "${SEED_TESTS[@]}"; do rm -f "$DEST/$f"; done
  echo "  · pruned ${#SEED_TESTS[@]} seed-data tests (the seed SQL is not exported)"
  # The browser lane, source only: the specs, the Playwright config and the stack script they boot. No
  # workflow runs it and `verify` does not call it - `npm run test:e2e`, by hand, is the only way in.
  rsync -a "${RSYNC_EXCL[@]}" e2e "$DEST/"
  cp -p playwright.config.ts "$DEST/"
  cp -p scripts/e2eStack.sh "$DEST/scripts/"
  echo "  · exported the browser lane (e2e/, playwright.config.ts, scripts/e2eStack.sh); it boots on"
  echo "    scripts/seed.sql + scripts/templates.sql, which are demo data and are NOT exported"
else
  # Without test/ the `deploy` script's `verify` step cannot pass, so narrow it to what still exists. The
  # browser lane goes with it: `typecheck` would otherwise open e2e/tsconfig.json, which is not there.
  node --input-type=module -e '
    import { readFileSync, writeFileSync } from "node:fs";
    const p = process.argv[1], pkg = JSON.parse(readFileSync(p, "utf8"));
    for (const s of ["test:e2e", "test:e2e:ui", "e2e:stack"]) delete pkg.scripts[s];
    pkg.scripts.typecheck = pkg.scripts.typecheck.replace(/\s*&&\s*tsc --noEmit -p e2e\/tsconfig\.json/, "");
    const left = Object.entries(pkg.scripts).filter(([, v]) => /(^|[^a-z])e2e/.test(v));
    if (left.length) {
      console.error("✗ package.json still points at the browser lane: " + left.map(([k]) => k).join(", "));
      process.exit(1);
    }
    pkg.scripts.verify = "npm run api:lint && npm run typecheck";
    delete pkg.scripts.test; delete pkg.scripts.precommit;
    writeFileSync(p, JSON.stringify(pkg, null, 2) + "\n");
  ' "$DEST/package.json"
  # test/ is where @types/node reaches the program (via vitest), and src uses `Buffer`. Drop the tests and
  # tsc loses that declaration - 10 TS2591 errors. Ask for the node types directly instead. @types/node is
  # already in the lockfile transitively, so this needs no dependency change.
  node --input-type=module -e '
    import { readFileSync, writeFileSync } from "node:fs";
    const p = process.argv[1];
    const src = readFileSync(p, "utf8")
      .replace(/"types":\s*\[[^\]]*\]/, `"types": ["@cloudflare/workers-types", "node"]`)
      .replace(/"include":\s*\[[^\]]*\]/, `"include": ["src"]`);
    writeFileSync(p, src);
  ' "$DEST/tsconfig.json"
  rm -f "$DEST/.husky/pre-commit"; rmdir "$DEST/.husky" 2>/dev/null || true
  echo '  · omitted test/ + the browser lane, narrowed `verify` to api:lint + typecheck (--no-tests)'
fi

echo "→ exported $(find "$DEST" -type f | wc -l | tr -d ' ') files, $(du -sh "$DEST" | cut -f1 | tr -d ' ')"

# --- closure scan: does anything exported import something that was not? -----------------------------------

node --input-type=module -e '
import { readdirSync, statSync, readFileSync, existsSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
const root = process.argv[1];
const files = [];
(function walk(d) {
  for (const e of readdirSync(d)) {
    if (e === "node_modules" || e === ".git") continue;
    const p = join(d, e);
    statSync(p).isDirectory() ? walk(p) : files.push(p);
  }
})(root);
// The one legitimate miss: api:types writes it at build time and .gitignore keeps it out of the repo.
const GENERATED = ["src/http/openapi.d.ts"];
const exts = ["", ".ts", ".tsx", ".js", ".mjs", ".jsx", ".json", "/index.ts", "/index.tsx"];
const hit = (base) => exts.some((e) => existsSync(base + e)) || GENERATED.some((g) => resolve(root, g).startsWith(base));
const missing = new Set();
for (const f of files.filter((f) => /\.(ts|tsx|mjs|js|jsx)$/.test(f))) {
  const src = readFileSync(f, "utf8"), rel = f.slice(root.length + 1);
  for (const m of src.matchAll(/(?:from|import)\s*\(?\s*["'"'"']([.][^"'"'"']+)["'"'"']/g)) {
    const spec = m[1].replace(/\?raw$/, "");
    if (!hit(resolve(dirname(f), spec))) missing.add(rel + " -> " + m[1]);
  }
  for (const m of src.matchAll(/from\s+["'"'"']@\/([^"'"'"']+)["'"'"']/g))
    if (!hit(resolve(root, "web/src", m[1]))) missing.add(rel + " -> @/" + m[1]);
  // `e2e` is in the list so the browser lane is held to the same rule as everything else: a spec that names
  // a file as data has to find it here. Under --no-tests the lane is gone and there is nothing to scan.
  for (const m of src.matchAll(/["'"'"'`]((?:src|web|scripts|bootstrap|test|e2e)\/[A-Za-z0-9_./-]+\.(?:ts|tsx|sql|json|yaml|toml|css|svg|png))["'"'"'`]/g))
    if (!existsSync(resolve(root, m[1]))) missing.add(rel + " READS " + m[1]);
}
if (missing.size) { console.error("✗ closure: " + missing.size + " dangling reference(s)\n  " + [...missing].join("\n  ")); process.exit(1); }
console.log("✓ closure: every relative and @/ import resolves inside the export");
' "$DEST"

# --- optional: run the real gate inside the export --------------------------------------------------------

if [ "$VERIFY" = 1 ]; then
  echo "→ verifying in $DEST (node_modules symlinked from this repo)"
  ln -sfn "$ROOT/node_modules" "$DEST/node_modules"
  # Each step runs quiet, but a failure re-runs it loud and stops: `set -e` does NOT fire on the left side of
  # an && list, so a silent `cmd >/dev/null && echo ✓` would let a broken export sail through to the commit.
  step() { # label, command...
    local label="$1"; shift
    if (cd "$DEST" && "$@" >/dev/null 2>&1); then
      echo "  ✓ $label"
    else
      echo "  ✗ $label FAILED - rerunning to show why:" >&2
      (cd "$DEST" && "$@") || true
      exit 1
    fi
  }
  step api:lint  npm run api:lint
  step typecheck npm run typecheck
  step build:web npm run build:web
  if [ "$TESTS" = 1 ]; then
    # Log outside the export so it can never be committed. Quiet on success, last 40 lines on failure.
    log="${TMPDIR:-/tmp}/hrms-export-vitest.log"
    if (cd "$DEST" && npx vitest run >"$log" 2>&1); then
      grep -E "Test Files|Tests +[0-9]" "$log" | sed 's/^ */  ✓ /'
    else
      echo "  ✗ vitest FAILED:" >&2; tail -40 "$log" >&2; exit 1
    fi
  fi
  rm -f "$DEST/node_modules"; rm -rf "$DEST/web/dist" "$DEST/src/http/openapi.d.ts"   # generated, not source
fi

# --- optional: make it a repo ------------------------------------------------------------------------------

if [ "$GIT" = 1 ]; then
  git -C "$DEST" init -q -b main
  git -C "$DEST" add -A
  git -C "$DEST" commit -q --no-verify -m "chore: initial deployable tree" \
    -m "Worker sources (src/), the SPA (web/), the production bootstrap catalog and the deploy workflows.
Dev tooling, docs, demo data and design assets are not part of the deploy and stay in the source repo."
  echo "✓ committed $(git -C "$DEST" rev-parse --short HEAD) on main ($(git -C "$DEST" ls-files | wc -l | tr -d ' ') files tracked)"
fi

cat <<EOF

Next:
  cd $DEST
  git remote add origin git@github.com:<org>/<repo>.git && git push -u origin main

Not exported, and not in git anywhere - set these on the Worker with \`wrangler secret put\`:
  SESSION_SECRET, GOOGLE_CLIENT_ID/SECRET, RESEND_API_KEY, VAPID_PRIVATE_KEY (see .dev.vars.example)
Also provision D1 \`hrms\`, R2 \`hrms\` and the KV namespaces wrangler.toml names, then apply
bootstrap/bootstrap.sql once to the empty database.
EOF
