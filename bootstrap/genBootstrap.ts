// Generates bootstrap/bootstrap.sql: the catalog + config a FRESH PRODUCTION database needs on day one.
// Thin orchestrator - each collection's data + SQL render lives in its own collections/*.ts module; this file
// just wires them in a fixed order (which keeps the shared id counter deterministic) and concatenates the
// blocks. DETERMINISTIC: fixed ids/timestamps, no Date.now/random, so re-running is byte-identical.
//
// What it deliberately does NOT seed: employees, departments, users (no demo identities, no login). The
// customer provisions their org and first admin out-of-band. This is the difference from scripts/seed.sql,
// the DEV/demo seed (100 fake employees + activity + 5 role logins).
//
//   Run:    node --import ./scripts/tsResolve.mjs bootstrap/genBootstrap.ts > bootstrap/bootstrap.sql
//   Apply:  npx wrangler d1 execute hrms --local --file=bootstrap/bootstrap.sql      (drop --local for remote)
import { createCtx, HOLIDAY_YEAR, FY_START_YEAR } from "./lib";
import { authz } from "./collections/authz";
import { leaveTypes } from "./collections/leaveTypes";
import { holidays } from "./collections/holidays";
import { reimbursementCategories } from "./collections/reimbursementCategories";
import { expenseCategories } from "./collections/expenseCategories";
import { payComponents } from "./collections/payComponents";
import { salaryStructures } from "./collections/salaryStructures";
import { payGrades } from "./collections/payGrades";
import { payPeriods } from "./collections/payPeriods";
import { benefitPlans } from "./collections/benefitPlans";
import { shifts } from "./collections/shifts";
import { boards } from "./collections/boards";
import { complianceRules } from "./collections/complianceRules";
import { settings } from "./collections/settings";
import { kudos } from "./collections/kudos";
import { templates } from "./collections/templates";
import { automations } from "./collections/automations";

const ctx = createCtx();
const fy = `${FY_START_YEAR}-${(FY_START_YEAR + 1) % 100}`;

// Built imperatively (not a single array literal) so each module's nid() calls fire in declaration order,
// keeping the shared id sequence stable. payComponents must run before salaryStructures and hand it the
// key->uuid map for the earning components.
const blocks: string[] = [
  "-- GENERATED by bootstrap/genBootstrap.ts (deterministic). Do not hand-edit; re-run the generator.",
  "-- India production bootstrap: catalog + config for a fresh DB. NO employees/departments/users.",
  `-- Holidays = calendar ${HOLIDAY_YEAR}; pay periods + tax = FY ${fy}.`,
];
blocks.push(authz());
blocks.push(leaveTypes(ctx));
blocks.push(holidays(ctx));
blocks.push(reimbursementCategories(ctx));
blocks.push(expenseCategories(ctx));
const { sql: payComponentsSql, uuidByKey } = payComponents(ctx);
blocks.push(payComponentsSql);
blocks.push(salaryStructures(ctx, uuidByKey));
blocks.push(payGrades(ctx));
blocks.push(payPeriods(ctx));
blocks.push(benefitPlans(ctx));
blocks.push(shifts(ctx));
blocks.push(boards(ctx));
blocks.push(complianceRules(ctx));
blocks.push(settings());
blocks.push(kudos());
blocks.push(templates());
blocks.push(automations(ctx));
blocks.push("");

process.stdout.write(blocks.join("\n") + "\n");
