// Generates only the automation rules from bootstrap/collections/automations.ts, for a database that is already
// bootstrapped and live: a rule added to the catalog after day one reaches it without regenerating the rest.
//
//   Run:    npm run -s bootstrap:automations -- "<rule name>" ["<rule name>" ...] > bootstrap/automations.sql
//   Apply:  npx wrangler d1 execute hrms --local --file=bootstrap/automations.sql      (swap --local for --remote)
//
// Name the rules to add. With no names it emits EVERY catalog rule, which also brings back any seeded rule an
// admin has since deleted, so name them unless the database has none of them.
//
// SAFE TO RE-RUN against a live database. Each rule is inserted only when no automation of that name exists, so
// a rule already there (and whatever an admin changed on it) is left alone; a rule an admin RENAMED is not
// recognised and would be added again. The code comes from the same place the app takes it (`code_sequences`,
// scope `automations`, the last value handed out) or, when that counter has never been touched, from the
// highest code stored; the counter is then moved past what was inserted, so the next rule created in the app
// does not collide. Codes are 2-character base32 (services/codeAlloc.ts CODE_WIDTH.flat), which holds 1024.
//
// NOT deterministic: each run mints fresh uuids and stamps the current time, like a create through the API.
import { AUTOMATIONS } from "./collections/automations";
import { q, b, j } from "./lib";
import { genId } from "../src/lib/idCodec";

const names = process.argv.slice(2);
const unknown = names.filter((name) => !AUTOMATIONS.some((a) => a.name === name));
if (unknown.length) {
  process.stderr.write(`No automation in bootstrap/collections/automations.ts is named:\n${unknown.map((n) => `  ${n}\n`).join("")}`);
  process.exit(1);
}
const picked = names.length ? AUTOMATIONS.filter((a) => names.includes(a.name)) : AUTOMATIONS;

// The base32 alphabet of domain/codes.ts, and a stored code's value in it. Only 2-character codes in that
// alphabet count, as in domain/codes.ts maxSeg: anything else is not a value the allocator could have produced.
const B32 = "'0123456789abcdefghjkmnpqrstvwxyz'";
const codeValue = `(instr(${B32}, substr(code, 1, 1)) - 1) * 32 + instr(${B32}, substr(code, 2, 1)) - 1`;
const isFlatCode = `length(code) = 2 AND instr(${B32}, substr(code, 1, 1)) > 0 AND instr(${B32}, substr(code, 2, 1)) > 0`;
const nextValue =
  `max(coalesce((SELECT next FROM code_sequences WHERE scope = 'automations'), -1), ` +
  `coalesce((SELECT max(${codeValue}) FROM automations WHERE ${isFlatCode}), -1)) + 1`;

const now = Date.now();
const inserts = picked.map(
  (a) =>
    "INSERT INTO automations (uuid,code,name,description,trigger_type,condition_json,actions_json,schedule_json,disabled,locked,created_at,updated_at)\n" +
    ` SELECT ${q(genId())}, substr(${B32}, v / 32 + 1, 1) || substr(${B32}, v % 32 + 1, 1), ${q(a.name)}, ${q(a.description)}, ${q(a.trigger)},` +
    ` ${a.condition ? j(a.condition) : "NULL"}, ${j(a.actions)}, ${a.schedule ? j(a.schedule) : "NULL"}, ${b(a.enabled === false)}, 0, ${now}, ${now}\n` +
    ` FROM (SELECT ${nextValue} AS v)\n` +
    ` WHERE NOT EXISTS (SELECT 1 FROM automations WHERE name = ${q(a.name)});`,
);
const bumpCounter =
  "INSERT INTO code_sequences (scope,next)\n" +
  ` SELECT 'automations', max(${codeValue}) FROM automations WHERE ${isFlatCode}\n` +
  " ON CONFLICT(scope) DO UPDATE SET next = max(code_sequences.next, excluded.next);";

process.stdout.write(
  [
    "-- GENERATED by bootstrap/genAutomations.ts. Adds the named catalog automations a database is missing (by name).",
    ...inserts,
    bumpCounter,
    "",
  ].join("\n"),
);
